"""Wrap the app's single FFmpeg-encoded HEVC frame as a primary HEIF image item."""
import struct


def box(kind, payload):
    return struct.pack(">I4s", len(payload) + 8, kind) + payload


def child(data, kind):
    offset = 0
    while offset + 8 <= len(data):
        size, tag = struct.unpack_from(">I4s", data, offset)
        if size < 8 or size > len(data) - offset:
            break
        if tag == kind:
            return data[offset + 8:offset + size]
        offset += size
    raise ValueError(f"Single-frame encoder output is missing {kind!r}.")


def save_still(mp4, output, width, height):
    # Only consume the one-frame, one-track MP4 just generated by movie encoding.
    data = mp4.read_bytes()
    sample = child(data, b"mdat")
    entry = data
    for kind in (b"moov", b"trak", b"mdia", b"minf", b"stbl", b"stsd"):
        entry = child(entry, kind)
    visual = child(entry[8:], b"hvc1")
    config = child(visual[78:], b"hvcC")
    coded_width, coded_height = struct.unpack_from(">HH", visual, 24)
    full = bytes(4)
    ftyp = box(b"ftyp", b"heic" + full + b"mif1heic")
    handler = box(b"hdlr", bytes(8) + b"pict" + bytes(12) + b"actual converter\0")
    primary = box(b"pitm", full + struct.pack(">H", 1))
    item = box(b"infe", bytes([2, 0, 0, 0]) + struct.pack(">HH", 1, 0) + b"hvc1Photo\0")
    info = box(b"iinf", full + struct.pack(">H", 1) + item)
    props = [box(b"hvcC", config), box(b"ispe", full + struct.pack(">II", coded_width, coded_height)),
             box(b"pixi", full + bytes([3, 8, 8, 8])),
             box(b"colr", b"nclx" + struct.pack(">HHHB", 1, 13, 1, 0))]
    associations = [0x81, 2, 3, 4]
    if (width, height) != (coded_width, coded_height):
        aperture = struct.pack(">IIIIiIiI", width, 1, height, 1, width-coded_width, 2, height-coded_height, 2)
        props.append(box(b"clap", aperture))
        associations.append(0x85)
    ipma = box(b"ipma", full + struct.pack(">IHB", 1, 1, len(associations)) + bytes(associations))
    properties = box(b"iprp", box(b"ipco", b"".join(props)) + ipma)

    def metadata(offset):
        # Version zero iloc, one item and one extent, 32-bit offset and length.
        location = box(b"iloc", full + struct.pack(">HHHHHII", 0x4400, 1, 1, 0, 1, offset, len(sample)))
        return box(b"meta", full + handler + primary + info + location + properties)

    meta = metadata(len(ftyp) + len(metadata(0)) + 8)
    with output.open("xb") as handle:
        handle.write(ftyp + meta)
        handle.write(box(b"mdat", sample))
